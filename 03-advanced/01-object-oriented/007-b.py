class سیستم_اتوماسیون:
    
    # 🔴 تغییر مهم: حالا هنگام ساخت سیستم، باید تنظیمات ارسال رو هم بهش بدیم
    def __init__(self, تنظیمات_پستچی):
        self.مغز_پردازشگر = پاسخ_دهنده_خودکار()
        self.لیست_تیکت_ها = []
        self.تنظیمات_ارسال = تنظیمات_پستچی  # 🟧 ذخیره کردن کارت ویزیت پستچی

    # متد پردازش که حالا ارسال واقعی می‌کند
    def دریافت_و_پردازش_کن(self, تیکت_جدید):
        # ۱. ثبت در تاریخچه
        self.لیست_تیکت_ها.append(تیکت_جدید)
        تیکت_جدید.وضعیت = "در_حال_پردازش"

        # ۲. ساخت پاسخ توسط مغز
        متن_پاسخ = self.مغز_پردازشگر.بساز_پاسخ(تیکت_جدید)
        
        # 🆕 ۳. ارسال واقعی ایمیل به فرستنده
        نتیجه_ارسال = ارسال_ایمیل_واقعی(
            تنظیمات=self.تنظیمات_ارسال,
            گیرنده=تیکت_جدید.فرستنده,        # ایمیل شخصی که تیکت زده
            موضوع=f"پاسخ خودکار به: {تیکت_جدید.موضوع}",
            متن_پیام=متن_پاسخ
        )

        # ۴. به‌روزرسانی وضعیت بر اساس نتیجه ارسال
        if نتیجه_ارسال:
            تیکت_جدید.وضعیت = "پاسخ_ارسال_شد"
        else:
            تیکت_جدید.وضعیت = "خطا_در_ارسال"

        return نتیجه_ارسال  # برمی‌گردونیم که موفق بود یا نه