# برنامه ای بنویسید که تعداد حروف  یک رشته را با خروجی مناسب چاپ کند
#توضیح صورت سوال (تعداد حروف یک رشته با خروجی مناسب یعنی چی؟)
#منظور از رشته (String)، همان متن یا کلماتی است که با کیبورد تایپ می‌کنید.
#وقتی سوال می‌گوید «تعداد حروف یک رشته را چاپ کند»، یعنی برنامه‌ای بنویسید که بشمارد داخل متنی که کاربر وارد کرده، چند تا کاراکتر (حرف، عدد یا حتی فاصله) وجود دارد.
#منظور از خروجی مناسب این است که برنامه فقط یک عدد خشک و خالی (مثلاً 5) چاپ نکند؛ بلکه یک پیام قشنگ و واضح بنویسد، مثل:
#The length of your text is: 5
#کد برنامه به همراه توضیح خط‌به‌خط:
#در پایتون یک ابزار (تابع) آماده به نام len() داریم که مخفف کلمه Length (به معنی طول یا تعداد) است. این تابع به راحتی تعداد حروف یک متن را می‌شمارد.
# دریافت متن از کاربر
user_text = input("Please enter a text: ")
# این خط یک متن یا کلمه را از کاربر می‌گیرد و در متغیر user_text ذخیره می‌کند

# شمارش تعداد حروف با استفاده از تابع len
count = len(user_text)
# تابع len تعداد حروف متنی که کاربر وارد کرده را می‌شمارد و عدد آن را در متغیر count می‌گذارد

# چاپ خروجی با یک پیام مناسب و زیبا
print("The number of characters in your text is:", count)
# این خط پیام راهنما را همراه با عدد به دست آمده در خروجی چاپ می‌کند