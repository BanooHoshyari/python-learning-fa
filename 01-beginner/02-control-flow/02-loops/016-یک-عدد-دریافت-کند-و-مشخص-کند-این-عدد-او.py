#برای اینکه بفهمیم یک عدد اول (Prime Number) هست یا نه، اول باید تعریف عدد اول را بدانیم:

#
#منطق برنامه این است: عدد ورودی را بر تمام اعداد از ۲ تا یکی کمتر از خودش تقسیم می‌کنیم. اگر بر هیچ‌کدام بخش‌پذیر نبود، یعنی عدد اول است.
# ۱. دریافت عدد از کاربر
number = int(input("Enter a number: "))
# عدد را از کاربر می‌گیرد و به نوع عددی صحیح تبدیل می‌کند

# ۲. تعریف یک متغیر پرچم (Flag) برای وضعیت اول بودن
is_prime = True
# در ابتدا فرض را بر این می‌گذاریم که عدد اول است (True)


# ۳. بررسی شرط اول (اعداد کوچکتر یا مساوی ۱ اول نیستند)
if number <= 1:
    is_prime = False
    # اگر عدد ۱ یا منفی یا صفر باشد، قطعاً اول نیست، پس پرچم False می‌شود

else:
    # ۴. شروع حلقه برای چک کردن بخش‌پذیری
    for i in range(2, number):
    # این حلقه اعداد ۲ تا یکی مانده به خود عدد را یکی‌یکی در i قرار می‌دهد

        if number % i == 0:
        # اگر باقی‌مانده تقسیم عدد بر i برابر با صفر شد (یعنی بخش‌پذیر بود):

            is_prime = False
            # متغیر پرچم را به False تغییر می‌دهد چون یک مقسوم‌علیه دیگر پیدا شده است
            
            break
            # چون مطمئن شدیم عدد اول نیست، با break از حلقه خارج می‌شویم


# ۵. چاپ خروجی مناسب با توجه به وضعیت پرچم
if is_prime == True:
    print(f"{number} is a prime number.")
    # اگر پرچم دست‌نخورده و True باقی مانده باشد، اعلام می‌کند عدد اول است

else:
    print(f"{number} is NOT a prime number.")
