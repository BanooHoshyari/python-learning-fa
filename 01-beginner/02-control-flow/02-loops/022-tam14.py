#کلمه و حرف را بگیرید و چاپ کند ایا حرف داخل ان کلمه هست یا نه و اینکه چند بار تکرار شده
# 1. گرفتن ورودی از کاربر برای کلمه
word = input("یک کلمه وارد کنید: ")

# 2. گرفتن ورودی از کاربر برای حرف
char_to_find = input("یک حرف برای جستجو وارد کنید: ")

# 3. مقداردهی اولیه برای شمارش تعداد تکرار حرف
count = 0

# 4. مقداردهی اولیه برای اینکه بفهمیم حرف پیدا شده است یا خیر
found = False

# 5. حلقه for برای پیمایش روی هر حرف از کلمه ورودی
for letter in word:
    # 6. بررسی اینکه آیا حرف فعلی در حلقه با حرف مورد نظر برای جستجو برابر است
    if letter == char_to_find:
        # 7. اگر حرف پیدا شد، شمارنده را یکی زیاد می‌کنیم
        count += 1
        # 8. چون حرف پیدا شد، پرچم 'found' را به True تغییر می‌دهیم
        found = True

# 9. بعد از اتمام حلقه for، نتیجه را بررسی می‌کنیم
if found:
    # 10. اگر 'found' برابر با True باشد، یعنی حرف پیدا شده است
    print(f"حرف '{char_to_find}' در کلمه '{word}' پیدا شد.")
    # 11. تعداد تکرار حرف را چاپ می‌کنیم
    print(f"این حرف {count} بار تکرار شده است.")
else:
    # 12. اگر 'found' برابر با False باشد، یعنی حرف پیدا نشده است
    print(f"حرف '{char_to_find}' در کلمه '{word}' پیدا نشد.")

