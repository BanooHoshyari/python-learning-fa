#جدول ضرب از 1 تا 9
# شروع حلقه بیرونی برای کنترل سطرها (از عدد 1 تا 9)
for i in range(1, 10):
# متغیر i در هر دور، شماره یکی از سطرها را برمی‌دارد (range تا یکی قبل از ۱۰ یعنی ۹ می‌رود)

    # شروع حلقه درونی برای کنترل ستون‌ها و محاسبات (از عدد 1 تا 9)
    for j in range(1, 10):
    # متغیر j در هر دور، ستون‌های سطر فعلی را می‌سازد

        # محاسبه ضرب و چاپ آن به صورت مرتب
        print(f"{i * j:4}", end="")
        # عدد حاصل‌ضرب را چاپ می‌کند. 
        # دستور :4 یعنی برای هر عدد ۴ کاراکتر فضا در نظر بگیر تا جدول صاف و مرتب بماند.
        # دستور end="" باعث می‌شود اعداد هر سطر پشت سر هم چاپ شوند و به خط بعد نروند.

    # رفتن به خط بعدی بعد از پایان هر سطر
    print()
    # وقتی حلقه درونی یک سطر را کامل چاپ کرد، این print خالی اجرا می‌شود تا سطر بعدی در خط جدید شروع شود.