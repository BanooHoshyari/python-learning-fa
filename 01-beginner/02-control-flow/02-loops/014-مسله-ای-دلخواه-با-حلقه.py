#مسله ای دلخواه با حلقه 
#یک مسئله بسیار رایج در دنیای واقعی، «بررسی وضعیت سرورها یا وب‌سایت‌های یک شرکت» است. فرض کنید مسئول آی‌تی یک شرکت هستید و باید هر روز صبح وضعیت ۱۰۰ سایت یا سیستم مختلف را چک کنید که آیا وصل هستند یا قطع؛ کاری بسیار خسته‌کننده!

#در ادامه، برنامه‌ای می‌نویسیم که این کار را با حلقه for به صورت خودکار انجام دهد.
# ۱. تعریف لیستی از سرورها یا وب‌سایت‌های شرکت
servers = ["سایت اصلی شرکت", "سرور حسابداری", "بانک اطلاعاتی", "سیستم حضور غیاب"]
# یک لیست (List) از سیستم‌هایی که باید وضعیتشان بررسی شود می‌سازیم

# ۲. شبیه‌سازی وضعیت سرورها (به عنوان مثال سرور حسابداری قطع است)
# در واقعیت این اطلاعات از اینترنت یا شبکه گرفته می‌شود
status_database = {
    "سایت اصلی شرکت": "Online",
    "سرور حسابداری": "Offline",
    "بانک اطلاعاتی": "Online",
    "سیستم حضور غیاب": "Online"
}

print("=== شروع فرآیند اتوماسیون بررسی وضعیت شبکه ===")

# ۳. شروع حلقه برای بررسی تک‌تک سرورها
for server in servers:
# این حلقه به تعداد سرورهای داخل لیست تکرار شده و در هر دور نام یک سرور را در متغیر server می‌گذارد

    print(f"در حال بررسی وضعیت: {server}...")
    
    # گرفتن وضعیت سرور فعلی از دیتابیس شبیه‌سازی شده
    current_status = status_database[server]

    # ۴. شرط برای بررسی قطعی یا وصلی
    if current_status == "Offline":
    # اگر وضعیت سرور برابر با Offline (قطع) بود:

        print(f"❌ هشدار خطای بحرانی: {server} از دسترس خارج شده است! ارسال پیامک به مدیر...")
        # یک پیام هشدار چاپ می‌کند (در کار واقعی در این بخش کد ارسال پیامک یا ایمیل قرار می‌گیرد)
        
    else:
    # اگر سرور وصل بود (Online):

        print(f"✅ {server} فعال و بدون مشکل است.")
        # تاییدیه سلامت سرور را چاپ می‌کند

print("=== پایان فرآیند اتوماسیون؛ تمام سیستم‌ها بررسی شدند ===")