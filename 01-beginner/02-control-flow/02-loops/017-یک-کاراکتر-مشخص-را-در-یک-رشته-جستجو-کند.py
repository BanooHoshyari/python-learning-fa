#یک کاراکتر مشخص را در یک رشته جستجو کند
# ۱. دریافت رشته و کاراکتر مورد نظر از کاربر
text = input("Enter the main text: ")
# متن اصلی را از کاربر می‌گیرد (مثلاً: python)

target_char = input("Enter the character to search for: ")
# کاراکتری که می‌خواهیم جایش را پیدا کنیم از کاربر می‌گیرد (مثلاً: t)


# ۲. تعریف یک متغیر پرچم (Flag) برای فهمیدن وضعیت جستجو
found = False
# در ابتدا فرض می‌کنیم کاراکتر پیدا نشده است، پس مقدار آن را False (غلط) می‌گذاریم


# ۳. شروع حلقه for برای گشتن در متن
for char in text:
# این حلقه تک‌تک حروف متن ورودی را یکی‌یکی برمی‌دارد و در متغیر char قرار می‌دهد

    if char == target_char:
    # بررسی می‌کند که آیا حرف فعلی، همان کاراکتری است که کاربر به دنبالش می‌گردد؟

        found = True
        # اگر پیدا شد، مقدار متغیر پرچم را به True (درست) تغییر می‌دهد
        
        break
        # چون کاراکتر را پیدا کردیم، با دستور break حلقه را متوقف می‌کنیم تا برنامه الکی ادامه پیدا نکند


# ۴. بررسی نتیجه و چاپ خروجی مناسب
if found == True:
# اگر در طول حلقه، کاراکتر پیدا شده باشد و مقدار found به True تغییر کرده باشد:

    print(f"Yes! The character '{target_char}' exists in the text.")
    # این پیام موفقیت‌آمیز را چاپ می‌کند

else:
# اگر حلقه تمام شده باشد اما هیچ‌وقت شرط داخل آن اجرا نشده باشد (یعنی found همان False باقی مانده باشد):

    print(f"No! The character '{target_char}' was not found in the text.")
    # این پیام را چاپ می‌کند که یعنی کاراکتر در متن وجود ندارد
    #یک مثال برای درک بهتر:
#فرض کنید متن ورودی کاربر "apple" باشد و کاراکتر مورد جستجو "p" باشد:

##حلقه در اولین دور حرف "a" را بررسی می‌کند. با "p" برابر نیست.

#در دور دوم حرف "p" را بررسی می‌کند. چون با "p" برابر است، متغیر found برابر با True می‌شود و حلقه با دستور break بلافاصله قطع می‌شود.

#در نهایت چون found درست است، پیام موفقیت چاپ می‌شود.