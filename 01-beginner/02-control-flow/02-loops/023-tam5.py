#رنامه ای بنویسید که یک رشته را دریافت کند و از طریق حلقه انرا معکوس کند
# دریافت رشته از کاربر
user_string = input("Enter a string: ")
# این خط یک متن را از کاربر می‌گیرد و در متغیر user_string ذخیره می‌کند

# ساخت یک متغیر خالی برای ذخیره رشته معکوس شده
reversed_string = ""
# یک رشته خالی می‌سازیم تا حروف معکوس شده را یکی‌یکی به آن اضافه کنیم

# شروع حلقه برای پیمایش تک‌تک حروف رشته ورودی
for char in user_string:
# این حلقه به تعداد حروف متنی که کاربر وارد کرده تکرار می‌شود و در هر دور، یک حرف را در متغیر char قرار می‌دهد

    reversed_string = char + reversed_string
    # این خط اصلی‌ترین بخش است؛ حرف جدید را به «ابتدای» رشته معکوس اضافه می‌کند تا متن برعکس شود

# چاپ نتیجه نهایی
print("Reversed string:", reversed_string)
# در نهایت متن معکوس شده را در خروجی نمایش می‌دهد