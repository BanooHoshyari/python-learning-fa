#تعداد تکرار هر حرف یک رشته را با دیکشنری محاسبه کند
def count_char_frequency(input_string):
  """
  این تابع تعداد تکرار هر حرف در یک رشته ورودی را با استفاده از دیکشنری محاسبه می‌کند.

  آرگومان‌ها:
    input_string (str): رشته‌ای که باید تجزیه و تحلیل شود.

  بازگشتی:
    dict: دیکشنری که در آن کلیدها حروف و مقادیر آنها تعداد تکرارشان است.
  """
  # 1. ایجاد یک دیکشنری خالی برای ذخیره شمارش حروف
  # چرا؟ ما از دیکشنری استفاده می‌کنیم چون ساختار کلید-مقدار آن برای نگاشت
  # هر حرف (کلید) به تعداد دفعات تکرارش (مقدار) ایده‌آل است.
  # دیکشنری‌ها جستجو، اضافه کردن و به‌روزرسانی را بسیار سریع انجام می‌دهند.
  char_counts = {}

  # 2. پیمایش بر روی هر حرف در رشته ورودی
  # چرا؟ باید تک تک حروف رشته را بررسی کنیم تا بتوانیم شمارش را انجام دهیم.
  # حلقه for به طور خودکار این کار را برای ما انجام می‌دهد.
  for char in input_string:
    # 3. به‌روزرسانی شمارش حرف فعلی در دیکشنری
    # چرا؟ برای هر حرف، می‌خواهیم تعداد تکرار آن را افزایش دهیم.
    #
    #   char_counts.get(char, 0):
    #     این قسمت سعی می‌کند مقدار (شمارش) مربوط به کلید 'char' را از دیکشنری
    #     'char_counts' دریافت کند.
    #     اگر 'char' قبلاً در دیکشنری وجود نداشته باشد (یعنی این اولین بار است
    #     که این حرف را می‌بینیم)، متد .get() به جای ایجاد خطا، مقدار پیش‌فرض
    #     '0' را برمی‌گرداند.
    #
    #   + 1:
    #     مقدار دریافتی (که یا شمارش قبلی حرف است یا '0' برای حرف جدید) با 1
    #     جمع می‌شود. این نشان‌دهنده یک تکرار بیشتر از این حرف است.
    #
    #   char_counts[char] = ...:
    #     نتیجه جمع (شمارش به‌روز شده) به عنوان مقدار کلید 'char' در دیکشنری
    #     'char_counts' ذخیره یا به‌روزرسانی می‌شود.
    #     اگر کلید 'char' قبلاً وجود نداشته باشد، ایجاد می‌شود. اگر وجود داشته
    #     باشد، مقدار قبلی آن با مقدار جدید جایگزین می‌شود.
    char_counts[char] = char_counts.get(char, 0) + 1

  # 4. بازگرداندن دیکشنری حاوی شمارش حروف
  # چرا؟ این دیکشنری همان نتیجه مورد نظر ماست که توسط تابع محاسبه شده و
  # باید به جایی که تابع فراخوانی شده، برگردانده شود تا قابل استفاده باشد.
  return char_counts
